    public function run(): void
    {
        $zones = [];

        foreach (self::ZONES as $name => $config) {
            $zones[$name] = ShippingZone::updateOrCreate(
                ['name' => $name],
                [
                    'cost' => $config['cost'],
                    'free_shipping_threshold' => $config['free_from'],
                    'delivery_days_min' => $config['days'][0],
                    'delivery_days_max' => $config['days'][1],
                    'is_active' => true,
                ],
            );
        }

        foreach (self::GOVERNORATES as $i => [$name, $nameEn, $code, $zone, $cities]) {
            $governorate = Governorate::updateOrCreate(
                ['name' => $name],
                [
                    'name_en' => $nameEn,
                    'code' => $code,
                    'shipping_zone_id' => $zones[$zone]->id,
                    'sort_order' => $i,
                    'is_active' => true,
                ],
            );

            foreach ($cities as $j => $city) {
                City::updateOrCreate(
                    ['governorate_id' => $governorate->id, 'name' => $city],
                    ['sort_order' => $j, 'is_active' => true],
                );
            }
        }
    }
