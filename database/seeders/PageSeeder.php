<?php

namespace Database\Seeders;

use App\Models\Page;
use Illuminate\Database\Seeder;

/**
 * The three pages a shop is expected to have before it takes an order: who it
 * is, what it does with the customer's data, and the terms of the sale.
 *
 * Seeded as a starting draft, not as fixed copy — the panel owns these from
 * here on, which is the whole point of them living in the database. Matched on
 * slug with firstOrCreate so re-running the seeders never overwrites wording an
 * admin has since corrected.
 *
 * The HTML is the subset the rich editor produces and .prose-shop styles: h2,
 * p, ul/ol, strong, a.
 */
class PageSeeder extends Seeder
{
    public function run(): void
    {
        foreach ($this->pages() as $page) {
            Page::firstOrCreate(['slug' => $page['slug']], $page);
        }
    }

    /**
     * @return array<int, array<string, mixed>>
     */
    private function pages(): array
    {
        return [
            [
                'slug' => 'about-us',
                'title' => 'من نحن',
                'menu_title' => 'من نحن',
                'meta_description' => 'متجر مصري للإكسسوارات والمشغولات، يوصّل لكل المحافظات مع الدفع عند الاستلام.',
                'sort_order' => 1,
                'content' => $this->aboutUs(),
            ],
            [
                'slug' => 'privacy-policy',
                'title' => 'سياسة الخصوصية',
                'menu_title' => 'الخصوصية',
                'meta_description' => 'ما نجمعه من بياناتك، وكيف نستخدمه، ومع من نشاركه، وحقوقك في تعديله أو حذفه.',
                'sort_order' => 2,
                'content' => $this->privacyPolicy(),
            ],
            [
                'slug' => 'terms',
                'title' => 'الشروط والأحكام',
                'menu_title' => 'الشروط والأحكام',
                'meta_description' => 'شروط الشراء والدفع عند الاستلام والشحن والاستبدال والاسترجاع.',
                'sort_order' => 3,
                'content' => $this->terms(),
            ],
        ];
    }

    private function aboutUs(): string
    {
        return <<<'HTML'
            <p>نحن متجر مصري متخصص في الإكسسوارات والمشغولات، بدأ بفكرة بسيطة: أن تحصل على قطعة تحبّها بسعر واضح ودون تعقيد.</p>

            <h2>ماذا نقدّم</h2>
            <ul>
                <li>تشكيلة مختارة من الخواتم والسلاسل والأطقم، بمقاسات وأطوال متعددة.</li>
                <li>أسعار معروضة كما هي — بدون رسوم تظهر في آخر خطوة.</li>
                <li><strong>الدفع عند الاستلام</strong> في كل محافظات مصر، فلا تدفع قبل أن ترى طلبك.</li>
                <li>شحن مجاني للطلبات فوق 1500 ج.م داخل القاهرة الكبرى.</li>
            </ul>

            <h2>كيف نختار منتجاتنا</h2>
            <p>نراجع كل قطعة قبل إضافتها: الخامة، وجودة التشطيب، وثبات اللون مع الاستخدام اليومي. وما لا نرضاه لأنفسنا لا نعرضه عليك.</p>

            <h2>تواصل معنا</h2>
            <p>فريق خدمة العملاء متاح للإجابة عن أي سؤال قبل الطلب أو بعده. تجد أرقام الهاتف والواتساب والبريد الإلكتروني في تذييل الموقع.</p>
            HTML;
    }

    private function privacyPolicy(): string
    {
        return <<<'HTML'
            <p>تشرح هذه الصفحة البيانات التي نجمعها عند استخدامك المتجر، وكيف نستخدمها، ومع من نشاركها. استخدامك للموقع يعني موافقتك على ما يلي.</p>

            <h2>البيانات التي نجمعها</h2>
            <ul>
                <li><strong>بيانات الحساب:</strong> الاسم والبريد الإلكتروني ورقم الهاتف وكلمة المرور (مُشفّرة ولا يمكن لأحد قراءتها، بما في ذلك فريقنا).</li>
                <li><strong>بيانات التوصيل:</strong> المحافظة والمدينة والعنوان التفصيلي، لإتمام الشحن.</li>
                <li><strong>بيانات الطلبات:</strong> ما اشتريته ومتى وبأي سعر، للمتابعة والاستبدال والاسترجاع.</li>
                <li><strong>بيانات تقنية:</strong> ملفات تعريف الارتباط اللازمة لتسجيل الدخول وحفظ سلة الشراء.</li>
            </ul>

            <h2>كيف نستخدمها</h2>
            <p>نستخدم بياناتك لتنفيذ طلبك وتوصيله، وللتواصل معك بشأنه، ولتحسين المتجر. <strong>لا نبيع بياناتك ولا نؤجّرها لأي طرف.</strong></p>

            <h2>مع من نشاركها</h2>
            <p>نشارك الاسم والهاتف والعنوان مع شركة الشحن المسؤولة عن طلبك — وبالقدر اللازم للتوصيل فقط. وقد نكشف عنها إذا طلبت ذلك جهة قضائية مختصة.</p>

            <h2>الدفع</h2>
            <p>المتجر يعمل بالدفع عند الاستلام، ولا نحتفظ ببيانات بطاقات بنكية على الإطلاق.</p>

            <h2>حقوقك</h2>
            <ul>
                <li>الاطلاع على بياناتك وتعديلها من صفحة حسابك في أي وقت.</li>
                <li>طلب حذف حسابك وبياناته، فيما لا يتعارض مع سجلات الطلبات التي يلزمنا الاحتفاظ بها.</li>
                <li>إلغاء الاشتراك في الرسائل التسويقية دون أن يتأثر تنفيذ طلباتك.</li>
            </ul>

            <h2>تحديث السياسة</h2>
            <p>قد نُحدّث هذه الصفحة، ويظهر تاريخ آخر تحديث في أعلاها. استمرارك في استخدام المتجر بعد التحديث يعني قبولك للنسخة المعروضة.</p>
            HTML;
    }

    private function terms(): string
    {
        return <<<'HTML'
            <p>تنظّم هذه الشروط العلاقة بينك وبين المتجر عند تقديم أي طلب. يُرجى قراءتها قبل الشراء.</p>

            <h2>الحساب</h2>
            <ul>
                <li>التصفّح وإضافة المنتجات للسلة متاح للجميع، أمّا إتمام الطلب فيستلزم حساباً حتى تتمكّن من متابعة طلبك.</li>
                <li>أنت مسؤول عن صحة بيانات التوصيل؛ العنوان الناقص قد يؤخّر الطلب أو يتعذّر معه التوصيل.</li>
                <li>أنت مسؤول عن الحفاظ على سرية كلمة المرور وعن أي نشاط يجري عبر حسابك.</li>
            </ul>

            <h2>الأسعار والطلبات</h2>
            <ul>
                <li>الأسعار بالجنيه المصري وتشمل قيمة المنتج، وتُحسب مصاريف الشحن حسب المحافظة وتُعرض قبل التأكيد.</li>
                <li>المعروض على الموقع عرضٌ للبيع، ولا يصبح الطلب مؤكداً إلا بتأكيدنا له.</li>
                <li>نحتفظ بحق إلغاء أي طلب عند نفاد المخزون أو وجود خطأ واضح في السعر، ونخبرك بذلك فوراً.</li>
                <li>الكميات محدودة بما هو متاح فعلاً في المخزون لكل مقاس أو لون.</li>
            </ul>

            <h2>الدفع والشحن</h2>
            <ul>
                <li><strong>الدفع عند الاستلام</strong> هو وسيلة الدفع المتاحة حالياً في كل المحافظات.</li>
                <li>الشحن مجاني للطلبات فوق 1500 ج.م داخل القاهرة الكبرى.</li>
                <li>مدة التوصيل تقديرية وتختلف بحسب المحافظة وظروف الشحن.</li>
                <li>لك حق فحص الطلب ظاهرياً عند الاستلام قبل الدفع.</li>
            </ul>

            <h2>الاستبدال والاسترجاع</h2>
            <ul>
                <li>يمكنك طلب الاستبدال أو الاسترجاع خلال <strong>14 يوماً</strong> من الاستلام، بشرط أن تكون القطعة بحالتها الأصلية وبكامل عبواتها.</li>
                <li>مصاريف إعادة الشحن على المتجر إذا كان العيب من المنتج، وعلى العميل إذا كان السبب تغيير الرأي.</li>
                <li>لا تُستبدل القطع المصنوعة بمقاس أو نقش خاص بناءً على طلبك.</li>
            </ul>

            <h2>التقييمات</h2>
            <p>التقييمات متاحة لمن اشترى المنتج فعلاً. ونحتفظ بحق حذف أي تقييم يحتوي إساءة أو بيانات شخصية أو محتوى دعائياً.</p>

            <h2>الملكية الفكرية</h2>
            <p>الصور والنصوص وتصميم المتجر مملوكة لنا، ولا يجوز استخدامها تجارياً دون إذن كتابي.</p>

            <h2>القانون المطبّق</h2>
            <p>تخضع هذه الشروط للقانون المصري، وتختص محاكم جمهورية مصر العربية بأي نزاع ينشأ عنها.</p>
            HTML;
    }
}
